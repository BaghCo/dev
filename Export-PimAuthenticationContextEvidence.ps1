#requires -Version 7.0
<#
.SYNOPSIS
    Optional authentication-context evidence for Azure PIM. Graph is opt-in.
.DESCRIPTION
    Offline mode (the default) reads the policy_settings.csv generated by
    Analyse-AzurePimPartial-v2.ps1, reports how many policies enable, disable or lack authentication-context rules,
    and records that Conditional Access enforcement has NOT been verified.

    Microsoft Graph is only contacted if -IncludeGraph is supplied. If consent or
    access is unavailable, Graph enrichment is skipped and the offline result is
    still retained. The visual HTML report itself can load the original CSV files
    directly, without running this helper at all.

    No Azure resources, identities, permissions or Conditional Access policies
    are modified. No empty Graph JSON files are fabricated on failure.
.EXAMPLE
    ./Export-PimAuthenticationContextEvidence.ps1 -PolicySettingsCsv './AzurePimAnalysis/policy_settings.csv'
.EXAMPLE
    ./Export-PimAuthenticationContextEvidence.ps1 -TenantId '00000000-0000-0000-0000-000000000000' -OutputDirectory './EntraEvidence'
    # Backwards-compatible invocation. Graph is skipped and consent is NOT requested.
.EXAMPLE
    ./Export-PimAuthenticationContextEvidence.ps1 -PolicySettingsCsv './AzurePimAnalysis/policy_settings.csv' -TenantId '00000000-0000-0000-0000-000000000000' -IncludeGraph
    # Opt-in only. Graph failures do not invalidate offline PIM evidence.
#>
[CmdletBinding()]
param(
    [string] $PolicySettingsCsv,
    [string] $OutputDirectory = (Join-Path (Get-Location).Path 'EntraEvidence'),
    [ValidatePattern('^[0-9a-fA-F]{8}-(?:[0-9a-fA-F]{4}-){3}[0-9a-fA-F]{12}$')]
    [string] $TenantId,
    [switch] $IncludeGraph
)

$ErrorActionPreference = 'Stop'
[void](New-Item -ItemType Directory -Path $OutputDirectory -Force)
$destination = (Resolve-Path -LiteralPath $OutputDirectory).Path

$status = [ordered]@{
    GeneratedUtc                   = [DateTime]::UtcNow.ToString('o')
    Mode                           = 'Offline'
    GraphAttempted                 = $false
    GraphEnrichment                = 'Not requested'
    EntraConditionalAccessVerified = $false
    PolicySettingsCsv              = ''
    PolicyRecordsRead              = 0
    ContextsReferenced             = 0
    Details                        = 'PIM CSVs can be loaded by Azure-PIM-Visual-Review.html without Graph.'
}

# Offline roll-up of the exact CSV fields written by Analyse-AzurePimPartial-v2.ps1.
# Report Yes, No and Unknown separately. Do not interpret an absent/disabled
# authentication context as evidence about unrelated Conditional Access policies.
if (-not [string]::IsNullOrWhiteSpace($PolicySettingsCsv)) {
    if (-not (Test-Path -LiteralPath $PolicySettingsCsv -PathType Leaf)) {
        throw "The specified policy_settings.csv could not be found: $PolicySettingsCsv"
    }

    $csvPath = (Resolve-Path -LiteralPath $PolicySettingsCsv).Path
    $status.PolicySettingsCsv = $csvPath
    $contextSummaries = @{}
    $flagCounts = [ordered]@{ Yes = [long]0; No = [long]0; Unknown = [long]0; Unexpected = [long]0 }
    $withIdCounts = [ordered]@{ Yes = [long]0; No = [long]0; Unknown = [long]0; Unexpected = [long]0 }
    $missingRuleCount = [long]0
    $enabledWithoutId = [long]0
    $csvColumnsChecked = $false

    Import-Csv -LiteralPath $csvPath | ForEach-Object {
        $record = $_
        if (-not $csvColumnsChecked) {
            $required = @('CAContextEnabled','CAContextId','ScopeId','Role','RuleCount')
            $existing = @($record.PSObject.Properties.Name)
            $missing = @($required | Where-Object { $_ -notin $existing })
            if ($missing.Count -gt 0) {
                throw "Input is missing expected CSV columns: $($missing -join ', '). Supply policy_settings.csv from Analyse-AzurePimPartial-v2.ps1."
            }
            $csvColumnsChecked = $true
        }
        $status.PolicyRecordsRead++

        $rawFlag = ([string]$record.CAContextEnabled).Trim()
        $flag = switch -Regex ($rawFlag) {
            '^(?i:yes|true|1)$'    { 'Yes'; break }
            '^(?i:no|false|0)$'    { 'No'; break }
            '^(?i:unknown|)$'     { 'Unknown'; break }
            default               { 'Unexpected' }
        }
        $flagCounts[$flag]++
        if ([string]$record.RuleCount -eq '0') { $missingRuleCount++ }

        $contextId = ([string]$record.CAContextId).Trim()
        # The PIM rule's claimValue is the context ID (often c1..c25). A
        # disabled rule may still have a claimValue, which is useful evidence.
        if ([string]::IsNullOrWhiteSpace($contextId)) {
            if ($flag -eq 'Yes') { $enabledWithoutId++ }
        }
        else {
            $withIdCounts[$flag]++
            $key = $contextId.ToLowerInvariant()
            if (-not $contextSummaries.ContainsKey($key)) {
                $contextSummaries[$key] = [pscustomobject]@{
                    ContextId   = $contextId
                    Enabled     = [long]0
                    Disabled    = [long]0
                    Unknown     = [long]0
                    Unexpected  = [long]0
                    Roles       = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
                    ScopeKinds  = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
                    ScopeIds    = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
                }
            }
            $item = $contextSummaries[$key]
            switch ($flag) {
                'Yes' { $item.Enabled++ }
                'No' { $item.Disabled++ }
                'Unknown' { $item.Unknown++ }
                default { $item.Unexpected++ }
            }
            if ($record.Role) { [void]$item.Roles.Add([string]$record.Role) }
            if ($record.ScopeKind) { [void]$item.ScopeKinds.Add([string]$record.ScopeKind) }
            if ($record.ScopeId) { [void]$item.ScopeIds.Add([string]$record.ScopeId) }
        }
    }

    $enabledContextIds = @($contextSummaries.Values | Where-Object { $_.Enabled -gt 0 }).Count
    $status.ContextsReferenced = $enabledContextIds
    $status['ContextIdsPresent'] = $contextSummaries.Count
    $status['AuthenticationContextFlagCounts'] = $flagCounts
    $status['ContextIdPresentByFlag'] = $withIdCounts
    $status['MissingPolicyRules'] = $missingRuleCount
    $status['EnabledWithoutContextId'] = $enabledWithoutId

    # One row per recorded ID, whether enabled or disabled. No imaginary
    # contexts are created when every source row lacks a context ID.
    $referenceRows = foreach ($item in ($contextSummaries.Values | Sort-Object Enabled -Descending)) {
        [pscustomobject]@{
            ContextId               = $item.ContextId
            EnabledPolicies         = $item.Enabled
            DisabledPolicies        = $item.Disabled
            UnknownPolicies         = $item.Unknown
            UnexpectedFlagPolicies  = $item.Unexpected
            DistinctScopes          = $item.ScopeIds.Count
            ScopeKinds              = (($item.ScopeKinds | Sort-Object) -join '; ')
            Roles                   = (($item.Roles | Sort-Object) -join '; ')
            ConditionalAccessStatus = 'Not verified: no Entra policy definitions in this CSV'
        }
    }
    $referencePath = Join-Path $destination 'pimAuthenticationContextReferences.csv'
    if ($contextSummaries.Count -eq 0) {
        'ContextId,EnabledPolicies,DisabledPolicies,UnknownPolicies,UnexpectedFlagPolicies,DistinctScopes,ScopeKinds,Roles,ConditionalAccessStatus' |
            Set-Content -LiteralPath $referencePath -Encoding utf8
    }
    else {
        $referenceRows | Export-Csv -LiteralPath $referencePath -NoTypeInformation -Encoding utf8
    }

    $flagSummaryPath = Join-Path $destination 'authenticationContextFieldSummary.csv'
    @(
        foreach ($key in @('Yes','No','Unknown','Unexpected')) {
            [pscustomobject]@{
                CAContextEnabled = $key
                PolicyRows       = $flagCounts[$key]
                RowsWithContextId = $withIdCounts[$key]
            }
        }
    ) | Export-Csv -LiteralPath $flagSummaryPath -NoTypeInformation -Encoding utf8

    Write-Host "PIM policy rows examined: $($status.PolicyRecordsRead)" -ForegroundColor Cyan
    Write-Host "CAContextEnabled: Yes=$($flagCounts['Yes']), No=$($flagCounts['No']), Unknown=$($flagCounts['Unknown']), Unexpected=$($flagCounts['Unexpected'])"
    Write-Host "Distinct context IDs recorded: $($contextSummaries.Count); enabled context IDs: $enabledContextIds; enabled rows with missing ID: $enabledWithoutId"
    Write-Host "Rows with zero rules: $missingRuleCount"
    Write-Host "Saved field diagnosis: $flagSummaryPath"
    Write-Host "Saved context reference detail: $referencePath"
    if ($flagCounts['Yes'] -eq 0) {
        Write-Warning 'No input rows have CAContextEnabled=Yes. This comes from policy_settings.csv, not a Graph or permission failure.'
        if ($flagCounts['Unknown'] -gt 0) {
            Write-Warning 'Some source records have unknown authentication-context status. Check whether the original JSONL contains AuthenticationContext_EndUser_Assignment rules.'
        }
    }
    if ($enabledWithoutId -gt 0) {
        Write-Warning "$enabledWithoutId policies say context enabled, but have no context ID. Validate these against the original policy rules."
    }
}
else {
    Write-Host 'No -PolicySettingsCsv supplied. Offline summary not generated.' -ForegroundColor Yellow
    Write-Host 'The visual HTML report reads the analyser CSVs directly; no exporter is needed.'
}

function Read-GraphCollection {
    param([Parameter(Mandatory)][string] $Uri)
    $items = [System.Collections.Generic.List[object]]::new()
    $next = $Uri
    $pages = 0
    while (-not [string]::IsNullOrWhiteSpace($next)) {
        $pages++
        if ($pages -gt 1000) { throw "Unexpectedly many pages for $Uri; aborting." }
        $body = Invoke-MgGraphRequest -Method GET -Uri $next -OutputType Json -ErrorAction Stop
        if ($body -is [string]) { $page = ConvertFrom-Json -InputObject $body -Depth 100 -ErrorAction Stop }
        else { $page = $body }
        if ($null -ne $page.value) {
            foreach ($item in @($page.value)) {
                if ($null -ne $item) { [void]$items.Add($item) }
            }
        }
        $next = [string]$page.'@odata.nextLink'
    }
    return $items.ToArray()
}

if ($IncludeGraph) {
    $status.GraphAttempted = $true
    $status.Mode = 'Offline with optional Graph enrichment'
    if ([string]::IsNullOrWhiteSpace($TenantId)) {
        $status.GraphEnrichment = 'Skipped: -TenantId was not specified'
        Write-Warning $status.GraphEnrichment
    }
    else {
        $connectedByScript = $false
        try {
            Import-Module Microsoft.Graph.Authentication -ErrorAction Stop
            Connect-MgGraph -TenantId $TenantId -Scopes 'Policy.Read.All','AuthenticationContext.Read.All' -ContextScope Process -NoWelcome -ErrorAction Stop | Out-Null
            $current = Get-MgContext
            if (-not $current -or $current.TenantId -ne $TenantId) {
                throw 'Graph connection is not in the requested tenant.'
            }
            $connectedByScript = $true

            $root = 'https://graph.microsoft.com/v1.0/identity/conditionalAccess'
            $contexts = @(Read-GraphCollection -Uri "$root/authenticationContextClassReferences")
            $policies = @(Read-GraphCollection -Uri "$root/policies")

            # Save both only after successful collection, to avoid mistaking a
            # failed or partial request for an authoritative empty export.
            $contextContent = [pscustomobject]@{value=@($contexts)} | ConvertTo-Json -Depth 80
            $policyContent = [pscustomobject]@{value=@($policies)} | ConvertTo-Json -Depth 80
            $contextContent | Set-Content -LiteralPath (Join-Path $destination 'authenticationContexts.json') -Encoding utf8
            $policyContent | Set-Content -LiteralPath (Join-Path $destination 'conditionalAccessPolicies.json') -Encoding utf8
            $status.GraphEnrichment = 'Collected'
            $status.Details = "Retrieved $($contexts.Count) authentication context definitions and $($policies.Count) Conditional Access policies. Effective enforcement has not been evaluated."
            Write-Host $status.Details -ForegroundColor Green
        }
        catch {
            $status.GraphEnrichment = 'Unavailable: authentication/consent/access or API error'
            $status.Details = 'Graph definitions were not retrieved. Use the PIM CSV report without Entra JSON enrichment.'
            Write-Warning "Graph enrichment skipped: $($_.Exception.Message)"
            Write-Warning 'The existing PIM CSV files remain usable without Microsoft Graph.'
        }
        finally {
            if ($connectedByScript -and (Get-Command Disconnect-MgGraph -ErrorAction SilentlyContinue)) {
                Disconnect-MgGraph -ErrorAction SilentlyContinue | Out-Null
            }
        }
    }
}
else {
    Write-Host 'Microsoft Graph skipped. No Graph connection or administrator consent requested.' -ForegroundColor Green
}


# Never treat files left by a previous run as evidence from this run.
if ($status.GraphEnrichment -ne 'Collected') {
    $existingGraphFiles = @('authenticationContexts.json','conditionalAccessPolicies.json') |
        Where-Object { Test-Path -LiteralPath (Join-Path $destination $_) -PathType Leaf }
    if ($existingGraphFiles.Count -gt 0) {
        Write-Warning 'Existing Entra JSON files were found in the output directory. They were NOT refreshed by this run and could be stale. Do not load them as current evidence without checking their origin.'
    }
}

$statusPath = Join-Path $destination 'authenticationContextEvidenceStatus.json'
([pscustomobject]$status | ConvertTo-Json -Depth 5) |
    Set-Content -LiteralPath $statusPath -Encoding utf8
Write-Host "Evidence status: $statusPath"
Write-Host 'For the visual report, select policy_settings.csv and other analyser CSVs. Entra JSON files are optional.' -ForegroundColor Cyan
